#include <string>
#include <vector>

void digit_sum() {
    int n = 9081;
    int total = 0;
    while (n > 0) {
        total += n % 10;
        n /= 10;
    }
    (void)total;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void sum_odds() {
    int acc = 0;
    for (int i = 1; i <= 10; ++i) {
        if (i % 2 != 0) acc += i;
    }
    (void)acc;
}

void small_factorial() {
    int result = 1;
    for (int i = 1; i <= 6; ++i) result *= i;
    (void)result;
}

extern "C" int prime_grove();
extern "C" void misty_meadow();
extern "C" void prime_meadow();

int main() {
    digit_sum();
    text_contains();
    sum_odds();
    small_factorial();
    misty_meadow();
    prime_meadow();
    return prime_grove();
}
